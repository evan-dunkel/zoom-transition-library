import { launch } from "./lib.mjs";
import { pathToFileURL } from "node:url";
const browser = await launch();
const page = await browser.newPage();
page.on("pageerror", (e) => console.log("pageerror:", e.message.slice(0, 120)));
page.on("framenavigated", (f) => console.log("navigated:", f === page.mainFrame() ? "MAIN" : "child", f.url().slice(0, 50)));
await page.goto("data:text/html,<p>previous page in history</p>");
await page.goto(pathToFileURL(process.cwd() + "/../demo/zoom-demo.html").href);
console.log("--- demo loaded; opening a card in the 'rapid' stage (history on)");
await page.locator("#s-rapid").scrollIntoViewIfNeeded(); await page.waitForTimeout(800);
const fr = await (await page.$('iframe[data-scenario="rapid"]')).contentFrame();
fr.on?.("console", () => {});
const errsInFrame = [];
await fr.evaluate(() => { window.addEventListener("error", (e) => (window.__errs = (window.__errs || []).concat(e.message))); });
await fr.click('[data-tile="rapid-2"]');
await page.waitForTimeout(1500);
console.log("frame errors:", await fr.evaluate(() => window.__errs || []).catch((e) => "frame gone: " + e.message.slice(0, 40)), "| phase:", await fr.evaluate(() => document.querySelector(".zoom-root")?.dataset.phase).catch(() => "?"));
console.log("--- pressing Esc to close");
await fr.evaluate(() => window.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape" }))).catch(() => {});
await page.waitForTimeout(1500);
console.log("main page URL now:", page.url().slice(0, 60));
await browser.close();
